package com.fluxecho.quest;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Base64;
import java.util.HashMap;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import org.junit.jupiter.api.Test;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

/**
 * The shipped quest lines have the shape QuestInjector and QuestInstaller rely on, and every line and quest 0.16.0
 * shipped is still there with the same key (its id is uuid5 of the key, and the players' progress hangs on the id),
 * the same place, prerequisites, tasks and rewards ({@code quest/0.16.0.json}, frozen). Only the text players read,
 * the names and descriptions, may change (0.17.0 rewrites it). The quests are generated by
 * {@code python quests/build_quests.py} from {@code quests/lines/*.py}.
 */
class QuestPackTest {

    private static final String ROOT = "/assets/fluxecho/quests/";

    @Test
    void everyLineIsCompleteAndShipped() throws IOException {
        JsonArray lines;
        try (Reader r = new InputStreamReader(open("index.json"), StandardCharsets.UTF_8)) {
            lines = new JsonParser().parse(r)
                .getAsJsonObject()
                .getAsJsonArray("lines");
        }
        assertFalse(lines.size() == 0, "no quest lines in index.json");
        for (JsonElement e : lines) {
            JsonObject line = e.getAsJsonObject();
            String order = line.get("order")
                .getAsString();
            String chapter = line.getAsJsonArray("dirs")
                .get(0)
                .getAsString();
            String quests = line.getAsJsonArray("dirs")
                .get(1)
                .getAsString();
            int lineFiles = 0;
            Set<String> placed = new TreeSet<>(), defined = new TreeSet<>();
            for (JsonElement f : line.getAsJsonArray("files")) {
                String path = f.getAsString();
                open("DefaultQuests/" + path).close();
                if (path.equals(chapter + "/QuestLine.json")) lineFiles++;
                else if (path.startsWith(chapter + "/")) placed.add(path.substring(chapter.length() + 1));
                else if (path.startsWith(quests + "/")) defined.add(path.substring(quests.length() + 1));
                else throw new AssertionError(path + " is outside the folders of " + order);
            }
            assertEquals(1, lineFiles, order + " needs exactly one QuestLine.json");
            assertFalse(defined.isEmpty(), order + " has no quests");
            assertEquals(defined, placed, order + ": every quest needs a position in the line and vice versa");
        }
    }

    /** The id namespace of quests/questkit.py. */
    static final String NS = "6f1c2d6a-3a0b-4b51-9a57-7f1d2e9c4b10";

    /** uuid5 of the key in the quests' namespace, as its two longs. */
    static long[] ids(String key) throws NoSuchAlgorithmException {
        java.util.UUID ns = java.util.UUID.fromString(NS);
        MessageDigest sha1 = MessageDigest.getInstance("SHA-1");
        sha1.update(
            ByteBuffer.allocate(16)
                .putLong(ns.getMostSignificantBits())
                .putLong(ns.getLeastSignificantBits())
                .array());
        byte[] h = sha1.digest(key.getBytes(StandardCharsets.UTF_8));
        h[6] = (byte) (h[6] & 0x0f | 0x50);
        h[8] = (byte) (h[8] & 0x3f | 0x80);
        ByteBuffer b = ByteBuffer.wrap(h, 0, 16);
        return new long[] { b.getLong(), b.getLong() };
    }

    static String b64(long[] id) {
        return Base64.getUrlEncoder()
            .encodeToString(
                ByteBuffer.allocate(16)
                    .putLong(id[0])
                    .putLong(id[1])
                    .array());
    }

    static JsonObject json(String path) throws IOException {
        return parse(open(path));
    }

    static JsonObject parse(InputStream in) throws IOException {
        try (Reader r = new InputStreamReader(in, StandardCharsets.UTF_8)) {
            return new JsonParser().parse(r)
                .getAsJsonObject();
        }
    }

    @Test
    void every016QuestIsStillShippedWithItsKeyAndItsWork() throws Exception {
        InputStream in = QuestPackTest.class.getResourceAsStream("/quest/0.16.0.json");
        assertNotNull(in, "missing the frozen quest/0.16.0.json");
        JsonObject frozen = parse(in);
        Map<String, JsonObject> shipped = new HashMap<>();
        for (JsonElement e : json("index.json").getAsJsonArray("lines")) {
            JsonObject line = e.getAsJsonObject();
            shipped.put(
                line.getAsJsonArray("dirs")
                    .get(0)
                    .getAsString(),
                line);
        }
        int quests = 0;
        for (JsonElement e : frozen.getAsJsonArray("lines")) {
            JsonObject old = e.getAsJsonObject();
            String key = old.get("key")
                .getAsString(),
                dir = old.get("dir")
                    .getAsString();
            long[] lineId = ids(key);
            assertEquals(
                b64(lineId),
                old.get("id")
                    .getAsString(),
                "the frozen id of " + key);
            assertTrue(dir.endsWith("-" + b64(lineId)), key + " lives in " + dir);
            JsonObject now = shipped.get("QuestLines/" + dir);
            assertNotNull(now, key + " (" + dir + ") is no longer shipped");
            assertEquals(old.get("requires"), now.get("requires"), key + ": the mods it needs");
            JsonObject lineFile = json("DefaultQuests/QuestLines/" + dir + "/QuestLine.json");
            assertEquals(
                lineId[0],
                lineFile.get("questLineIDHigh:4")
                    .getAsLong(),
                key);
            assertEquals(
                lineId[1],
                lineFile.get("questLineIDLow:4")
                    .getAsLong(),
                key);
            for (JsonElement qe : old.getAsJsonArray("quests")) {
                JsonObject q = qe.getAsJsonObject();
                String qkey = q.get("key")
                    .getAsString(),
                    file = q.get("file")
                        .getAsString();
                long[] id = ids(qkey);
                assertEquals(
                    b64(id),
                    q.get("id")
                        .getAsString(),
                    "the frozen id of " + qkey);
                JsonObject data = json("DefaultQuests/Quests/" + dir + "/" + file);
                assertEquals(
                    id[0],
                    data.get("questIDHigh:4")
                        .getAsLong(),
                    qkey);
                assertEquals(
                    id[1],
                    data.get("questIDLow:4")
                        .getAsLong(),
                    qkey);
                JsonObject props = data.getAsJsonObject("properties:10")
                    .getAsJsonObject("betterquesting:10");
                props.remove("name:8");
                props.remove("desc:8");
                assertEquals(q.get("quest"), data, qkey + ": only its name and description may change");
                JsonObject at = json("DefaultQuests/QuestLines/" + dir + "/" + file);
                assertEquals(q.get("x"), at.get("x:3"), qkey + " x");
                assertEquals(q.get("y"), at.get("y:3"), qkey + " y");
                assertEquals(
                    id[0],
                    at.get("questIDHigh:4")
                        .getAsLong(),
                    qkey);
                quests++;
            }
        }
        assertEquals(83, quests, "0.16.0 shipped 83 quests");
    }

    private static InputStream open(String path) {
        InputStream in = QuestPackTest.class.getResourceAsStream(ROOT + path);
        assertNotNull(in, "missing resource " + ROOT + path);
        return in;
    }
}
